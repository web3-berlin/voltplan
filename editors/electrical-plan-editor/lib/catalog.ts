export function electricalCategoryColor(id: string): string {
  if (id === "distribution") return "#475569";
  if (id === "outlet") return "#2563eb";
  if (id === "switch") return "#7c3aed";
  if (id === "lighting") return "#d97706";
  if (id === "appliance") return "#dc2626";
  if (id === "data") return "#0891b2";
  if (id === "safety") return "#ea580c";
  if (id === "hvac") return "#0d9488";
  if (id === "knx") return "#16a34a";
  return "#6b7280";
}
