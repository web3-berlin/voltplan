const pt = (x: number, y: number) => ({ x, y });

function L(
  points: [number, number][],
  opts: { closed?: boolean; fill?: boolean; stroke?: boolean } = {},
): SymbolPart {
  return { kind: "line", points: points.map(([x, y]) => pt(x, y)), ...opts };
}
function C(
  cx: number,
  cy: number,
  r: number,
  opts: { fill?: boolean; stroke?: boolean } = {},
): SymbolPart {
  return { kind: "circle", cx, cy, r, ...opts };
}
function A(
  cx: number,
  cy: number,
  r: number,
  start: number,
  end: number,
): SymbolPart {
  return { kind: "arc", cx, cy, r, start, end };
}
function R(
  x: number,
  y: number,
  w: number,
  h: number,
  opts: { fill?: boolean; stroke?: boolean } = {},
): SymbolPart {
  return { kind: "rect", x, y, w, h, ...opts };
}
function T(
  x: number,
  y: number,
  text: string,
  size = 5,
  weight: "normal" | "bold" = "bold",
): SymbolPart {
  return { kind: "text", x, y, text, size, weight };
}

